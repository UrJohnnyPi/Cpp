/*
题目：写一个函数，求两个整数之和，要求在函数体内不得使用＋、－、×、÷
四则运算符号。
分析：
因不能采用＋、－、×、÷，故只能采用位运算。
先分析下十进制数的加法运算，以5+17为例。
5+17=12+10，即无进位的部分+进位=val。
同理：
5->101
17->10001
101+10001 = 10100 + 10=10110
现在就是要去思考看看利用位运算符是否能够得出 10100和10。得到101+10001->10100 + 10后，
就又转换成了10100 + 10->？的问题。这个循环直到进位部分为0，此时进位的部分^进位=val。
 10001
+  101
------
 10110 -> 10100 + 10

 10001   10001
^  101  &  101
------  ------
 10100   00001 << 00010
即先xor，后&加<<就能得到无进位和进位两个部分。

*/
#include <iostream>
using namespace std;

int add(int a , int b) {
	int sum , carry;
	
	do {
		sum = a ^ b;
		carry = (a & b) << 1;

		a = sum;
		b = carry;
	} while(b != 0);

	return a;
}

int main() {
	cout << add(5 , 17);
	return 0;
}
