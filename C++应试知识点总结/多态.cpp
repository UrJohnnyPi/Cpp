/*
二：运行期多态 之 绑定
静态类型：静态类型就是 定义/声明 变量的类型。
动态类型：动态类型是变量 实际 的类型，即变量值的类型。
静态类型决定了基类指针（或引用）调用哪个类中的成员函数合法；动态类型决定了运行期间，基类指针（或引用）将指向哪个重写的函数。

静态绑定：又名 前期（编译期）绑定。静态绑定由静态类型决定，意即，对于那些 在函数运行前（编译期） 就得确定下来的操作，若这些操作的确定必须考虑到某一变量的类型，则考虑该变量的静态类型。
动态绑定：又名 后期（运行期）绑定。动态绑定由动态类型决定，意即，在函数运行到某一操作前（运行期）才去确定要具体选择哪一操作，而具体选择哪一操作又依赖于某一变量的类型，这时，根据该变量的动态类型来选择。
	virtual函数是动态绑定，因此virtual函数的选择依赖对象的动态类型。
	缺省参数值是静态绑定，因此缺省参数的选择依赖对象的静态类型。
	***************************
	class Base{
		public :
			virtual void fun(int var = 7){
				cout << "Base" << ends << var;
			}
	};
	class Derived : public Base{
		public :
			void fun(int var = 5){
				cout << "Derived" << ends << var;
			}
	};
	
	Derived d;
	Base * b = & d;
	b->fun(); //输出Derived 7
	***************************
	这里要分外注意的是：若派生类中具有与基类中虚函数同名的函数，不论派生类是否对该函数加virtual关键字，系统都会：
	（a）检查该函数的形参个数及形参类型是否与基类中虚函数的相同。
	（b）若相同，则继续检查该函数是否与基类中的虚函数有相同的返回值类型或者满足赋值兼容规则的指针、引用型的返回值。
	（c）若相同，则派生类中的该函数为隐式的虚函数。派生类中的该函数将覆盖从基类中继承而来的同名虚函数。
	鉴于此，倘若有：
	***************************
	class Base{
		public :
			virtual void fun(int var = 7){
				cout << "Base" << ends << var;
			}
	};
	class Derived : public Base{
		public :
			void fun(int var , char ch){ //或：int fun(int var)
				cout << "Derived" << ends << var1;
			}
	};
	***************************
	则，Derived::fun不是对Base::fun的重写，Derived::fun只是对Base::fun的简单的同名隐藏，和virtual无关。意即Derived d; Base * b = & d; b->fun();输出：Base 7

见《Effective C++》条款37
*/

/*
三：运行期多态 之 虚函数（表） 和 要满足的要求
1.虚函数表：
	欲实现出virtual函数，对象必须携带某些信息，主要用来在运行期决定哪一个virtual函数该被调用。
	这份信息通常是由“虚函数表指针”vptr(virtual table pointer)指出。vptr指向一个由函数指针构成
	的数组，称为vtbl(virtual table)即虚函数表。每一个带有virtual函数的class都有一个相应的vtbl。
	当对象调用某一virtual函数，实际被调用的函数取决于该对象的vptr所指的那个vtbl——编译器在其中
	寻找适当的函数指针。

	同属一个类的不同的实例化对象共用一张虚函数表。
	基类虚函数表和派生类虚函数表的关系：
		若派生类中重写了虚函数，则派生类维护着一张不同与基类虚表的虚表（虚表指针当然也不同），派生类的虚表中的虚函数地址也 不同。
		若派生类中没有重写虚函数（即直接继承），则派生类维护着一张不同与基类虚表的虚表（虚表指针当然也不同），派生类的虚表中的虚函数地址 相同。
2.运行期多态要满足的要求：
	（1）类之间满足赋值兼容规则（即继承关系）
	（2）声明虚函数（即使用virtual关键字）
			倘若没有这个约束，则：
			***************************
			class A{
				public :
					void fun();
			}; 
			class B : public A{
				public :
					void fun();
			};
			
			B b;
			A * pa = & b;
			B * pb = & b;
			pa->fun(); //A::fun()
			pb->fun(); //B::fun()
			***************************
	（3）要由成员函数来调用或者是通过指针、引用来访问虚函数。（例子：对于class B : public A{virtual fun();}; 有：A * a = & b; 或 A & a = b;）
			***************************
			#include <iostream>
			using namespace std;
			class A{
				public :
					void test(){
						display(); //相当于 this->display(); 而this就是a。
					}
					virtual void display(){
						cout << "A";
					}
			};
			class B : public A{
				public :
					void display(){
						cout << "B";
					}
			};
			int main(){
				B b;
				A * a = & b;
				a->display();
				return 0;
			}
			***************************
*/

/*
四：运行期多态 之 （拷贝）构造、析构函数 和 虚函数
1.（拷贝）构造函数不能是虚函数：
	调用构造函数构造对象时（要调用，还未调用），虚函数表尚未生成（构造函数执行完毕时，虚函数表才能建立），编译器执行构造函数遇到virtual关键字，无法得知选用哪一个重写的构造函数。
2.析构函数可以是虚函数：
	有意向充当基类的类，其析构函数应被声明为virtual。这里的“有意向”表达了两点：（1）不是所有析构函数都要声明为virtual，因其有虚函数指针和虚函数表的开销。（2）当有一成员函数为virtual时，该类视为“有意向充当基类”的类。

3.（拷贝）构造函数不能调用虚函数：
	（1）对象构造期间（构造函数执行时），虚函数表尚未建立完成，编译器无法确定运行哪一虚函数。
	（2）运行期多态就是【将一个 Derived对象取地址/Derived指针 赋给Base指针：A * a = &b;/A * a = bptr;】 或 【将一个Derived对象赋值给一个Base引用：A & a = b;】，所以必然有先构造一个Derived对象的过程，
		 但Derived对象的构造是回字形（由内向外）构造，在构造其内部基类部分时，其外部派生类部分尚未开始构造（即Derived构造函数先调用Base构造函数，之后才构造派生部分），因此，若构造函数调用虚函数，是
		 不会执行Derived重写的虚函数的，因为其派生部分还没被初始化，编译器不知道派生部分的情况。
4.析构函数不能调用虚函数：
	（1）若在析构函数中调用虚函数，析构函数执行，虚函数表会被删除，因此不会执行重写的虚函数。
	（2）派生类对象被析构时，满足回字形析构过程（由外向内），即基类空间外部的派生空间先被析构，所以在执行基类析构函数中的虚函数时，也就无法执行一个被析构空间中的虚函数。
5.构造函数和析构函数调用的函数也不能调用虚函数。
*/

/*
五：运行期多态 之 内在本质（内存）
1.运行期多态：定义你的类型决定了你可以调用哪个类中的成员函数，而你实际具有的值决定了你将使用哪个类中的重写函数。
2.运行期多态实现了：通过一个基类指针/引用，可以访问不同派生类中的函数。即通过一个接口，实现多种功能。
2.内存本质：基类指针（引用） 指向（绑定）了 派生类对象的内存空间。
  要义：两个类必须是继承关系；基类指针（引用） 指向（绑定）了 派生类对象的内存空间（这就表明，要用派生类对象赋值给基类引用 或 派生类（指针）地址赋值给基类指针）。
  
《Effective C++》条款20
*/

/*
六：接口继承 和 实现继承
1.只继承成员函数的接口：Derived只继承Base成员函数的接口（即Base的函数声明）。对应pure virtual。 
	当你需要一个抽象类作为泛化接口，但当前还没有适合的纯虚函数供选择，那就把析构函数声明为纯虚函数，但要在类外给出析构函数的定义式，避免连接时错误。（倘若没有类外的定义式，派生类的析构函数会因为调用基类的无实现纯虚析构函数而在连接函数体时报错）
	要学会使用并理解这种技巧：
	***************************
	class Base{
		public :
			virtual T fun() = 0;
	};
	T Base::fun(){
		//do something
	}
	
	class Derived1 : public Base{
		public :
			T fun(){
				Base::fun(); //因为Derived1::fun可以默认采用Base::fun，因此若来不及为Derived1重写fun，就使用继承而来的fun
			}
	};
	
	class Derived2 : public Base{
		public :
			T fun(){
				//own code //因为Derived2::fun需要完全重写fun接口，因此这里无论何时也不能将Base::fun的作用域扩展至此。
			}
	};
	***************************
	上述代码的关键在fun被分割为两个基本要素：其声明部分表现的是接口，其定义部分表现为缺省。通过继承关系，继承的是基类成员的声明式；通过作用域分辨符访问的是基类成员的定义式。
	
2.继承成员函数的接口，并希望能重写实现。对应impure virtual。
3.继承成员函数的接口和实现，不希望重写。对应non virtual。

见《Effective C++》条款07、条款34
*/