/*
条款09：绝不在构造和析构过程中调用virtual函数

1.构造函数中不能调用virtual函数：（base构造期间，virtual函数不是virtual函数） 
（1）在“C++应试知识点总结/构造函数、析构函数、虚函数相关”中提到的原因是：
构造函数中调用虚函数，显示的是本类中的虚函数，而不会被派生类中
重写的虚函数取代，因为构造函数在定义对象时，虚函数表还没有建立，虚函数关系还没有
绑定。
（2）另一个原因是：
派生类对象在构造时符合回字形构造，即先构造base部分，再构造derived部分。构造base部分时，
derived部分的数据成员尚未初始化，如果此时允许virtual函数发挥作用，则必然要调用
derived中重写的那个virtual，但derived部分的数据成员还没有初始化，如果derived中
的virtual使用了derived中的数据成员，则会产生异常。 

析构函数中不能调用virtual函数：
（1）在“C++应试知识点总结/构造函数、析构函数、虚函数相关”中提到的原因是：
在析构函数中调用虚函数，虚函数表被删除，而且基类空间外部的派生空间被析构，所以也就
不会调用派生类中重写的函数。
（2）另一个原因是：
derived对象满足回字形析构，当derived部分被析构后，derived部分的数据成员呈现尚未
初始化状态。因此，若在base的析构函数中调用虚函数，则犯了和上述一样的错误。

2.构造函数和析构函数不能调用虚函数，构造函数和析构函数调用的函数也不能调用虚函数。 
*/
