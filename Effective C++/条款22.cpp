/*
条款22：将成员变量声明为private

原因：
（1）一致性，如果public下都是函数，而不出现数据成员，那客户就不需要考虑调用的是函数还是数据了。
（2）当将数据成员全部声明为private时，你就可以设定其访问权限，readonlay或是writeonly等等，但一旦暴露在public下，所有客户都可读可写。
（3）出于封装目的。将数据成员写在private下，日后的修改中，不影响使用着的客户，因为客户访问的是public下的函数，而函数接口一般不易变动。
但若将数据成员写到public下，一个改动会波及大量客户。事实上，写在public下的成员总会影响使用它的客户，写在protected下的成员总会影响derived class。
所以不论public还是protected下的成员，一旦出问题，都波及广泛。
private是封装的保障。 
*/
